export async function shareOrderLabelsPdf(params: ShareOrderLabelsParams): Promise<void> {
  if (params.items.length === 0) {
    throw new Error(
      params.locale === 'pt-BR'
        ? 'Nenhum aparelho selecionado para gerar etiqueta.'
        : 'No items selected to generate labels.'
    );
  }

  const html =
    params.mode === 'THERMAL_58MM'
      ? buildThermal58LabelsHtml(params)
      : buildA4LabelsHtml(params);

  const single = params.items.length === 1 ? params.items[0] : null;
  const suffix = single ? single.tag : `OS-${params.order.orderNumber}`;
  const sizeTag = params.mode === 'THERMAL_58MM' ? '58mm' : 'A4';
  const filename = `BenchOS_Etiqueta_${suffix}_${sizeTag}.pdf`;
  const dialogTitle =
    params.locale === 'pt-BR'
      ? `Etiqueta #${suffix} (${sizeTag})`
      : `Label #${suffix} (${sizeTag})`;

  await renderAndSharePdf(html, filename, dialogTitle);
}

