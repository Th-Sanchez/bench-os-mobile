const VOLTAGE_LABELS: Record<Voltage, { pt: string; en: string }> = {
  V110: { pt: '110V', en: '110V' },
  V220: { pt: '220V', en: '220V' },
  BIVOLT: { pt: 'BIVOLT', en: 'BIVOLT' },
  BATTERY: { pt: 'BATERIA', en: 'BATTERY' },
  UNKNOWN: { pt: 'N/I', en: 'N/A' },
};

function escapeHtml(raw: string | null | undefined): string {
  return String(raw ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function formatDateShort(iso: string | null | undefined, locale: Locale): string {
  if (!iso) return '—';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso.slice(0, 10);
  const dd = String(d.getDate()).padStart(2, '0');
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const yyyy = d.getFullYear();
  return locale === 'en' ? `${yyyy}-${mm}-${dd}` : `${dd}/${mm}/${yyyy}`;
}

function formatVoltage(voltage: Voltage, locale: Locale): string {
  const entry = VOLTAGE_LABELS[voltage] ?? VOLTAGE_LABELS.UNKNOWN;
  return locale === 'en' ? entry.en : entry.pt;
}

/**
 * Generates a pure inline SVG string synchronously and 100% offline using `qrcode`,
 * so thermal and A4 labels render razor-sharp QR codes with zero network calls.
 */
export function buildQrCodeSvg(content: string): string {
  const qr = QRCode.create(content, { errorCorrectionLevel: 'M' });
  const size = qr.modules.size;
  const data = qr.modules.data;
  const margin = 2;
  const total = size + margin * 2;

  const rects: string[] = [];
  for (let row = 0; row < size; row += 1) {
    for (let col = 0; col < size; col += 1) {
      if (data[row * size + col]) {
        rects.push(`M${col + margin},${row + margin}h1v1h-1z`);
      }
    }
  }

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${total} ${total}" shape-rendering="crispEdges"><rect width="${total}" height="${total}" fill="#FFFFFF"/><path d="${rects.join('')}" fill="#000000"/></svg>`;
}

export function buildItemTrackingQrUrl(publicToken: string, itemIndex?: number): string {
  const base = `${API_BASE_URL.replace(/\/$/, '')}/track/${publicToken}`;
  return typeof itemIndex === 'number' && itemIndex > 0 ? `${base}?item=${itemIndex}` : base;
}

export interface ParsedBenchQr {
  publicToken: string;
  itemIndex?: number;
}

const UUID_REGEX =
  /([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})/i;

/**
 * Parses QR payloads generated by BenchOS labels or public tracking URLs:
 * - https://api.benchos.app.br/track/{uuid}?item=2
 * - https://api.benchos.app.br/track/{uuid}/receipt
 * - benchos://track/{uuid}?item=1
 * - raw UUID
 */
export function parseBenchQrPayload(raw: string): ParsedBenchQr | null {
  const trimmed = raw.trim();
  if (!trimmed) return null;

  const uuidMatch = trimmed.match(UUID_REGEX);
  if (!uuidMatch) return null;

  const publicToken = uuidMatch[1].toLowerCase();
  let itemIndex: number | undefined;

  try {
    const queryIndex = trimmed.indexOf('?');
    if (queryIndex !== -1) {
      const search = new URLSearchParams(trimmed.slice(queryIndex + 1));
      const rawItem = search.get('item');
      if (rawItem) {
        const parsed = Number.parseInt(rawItem, 10);
        if (Number.isFinite(parsed) && parsed > 0) {
          itemIndex = parsed;
        }
      }
    }
  } catch {
    // Ignore malformed query string; publicToken alone still resolves the order
  }

  return { publicToken, itemIndex };
}

function printHtmlInWebIframe(html: string): Promise<void> {
  return new Promise((resolve, reject) => {
    const iframe = document.createElement('iframe');
    iframe.style.position = 'fixed';
    iframe.style.right = '0';
    iframe.style.bottom = '0';
    iframe.style.width = '0';
    iframe.style.height = '0';
    iframe.style.border = '0';
    iframe.style.visibility = 'hidden';

    let cleaned = false;
    const cleanup = () => {
      if (cleaned) return;
      cleaned = true;
      setTimeout(() => {
        if (iframe.parentNode) {
          iframe.parentNode.removeChild(iframe);
        }
      }, 500);
    };

    iframe.onload = () => {
      try {
        const win = iframe.contentWindow;
        if (!win) {
          cleanup();
          reject(new Error('Could not open print frame'));
          return;
        }
        win.onafterprint = () => {
          cleanup();
        };
        win.focus();
        win.print();
        setTimeout(cleanup, 30_000);
        resolve();
      } catch (err) {
        cleanup();
        reject(err);
      }
    };

    document.body.appendChild(iframe);
    const frameDoc = iframe.contentDocument ?? iframe.contentWindow?.document;
    if (!frameDoc) {
      cleanup();
      reject(new Error('Could not access print document'));
      return;
    }
    frameDoc.open();
    frameDoc.write(html);
    frameDoc.close();
  });
}

async function renderAndSharePdf(
  html: string,
  filename: string,
  dialogTitle: string
): Promise<void> {
  if (Platform.OS === 'web') {
    await printHtmlInWebIframe(html);
    return;
  }

  const { uri, base64 } = await Print.printToFileAsync({
    html,
    base64: true,
  });

  const targetFile = new File(Paths.cache, filename);
  let shareUri = uri;

  if (base64) {
    targetFile.write(base64, { encoding: 'base64' });
    shareUri = targetFile.uri;
  } else {
    try {
      const generatedFile = new File(uri);
      generatedFile.copy(targetFile, { overwrite: true });
      if (targetFile.exists && targetFile.size > 0) {
        shareUri = targetFile.uri;
      }
    } catch {
      shareUri = uri;
    }
  }

  const canShare = await Sharing.isAvailableAsync();
  if (!canShare) {
    await Print.printAsync({ uri: shareUri });
    return;
  }

  await Sharing.shareAsync(shareUri, {
    mimeType: 'application/pdf',
    dialogTitle,
    UTI: 'com.adobe.pdf',
  });
}

